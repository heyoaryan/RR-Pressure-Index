"""Writes frontend/data.js from ../dashboard_data.json and refreshes the static (no-JS)
top-10 tables inside frontend/index.html, between the STATIC-TOP10 markers.

Run after re-running the analysis:
    python3 dashboard/build_data.py
"""
import json, os, re, html

HERE = os.path.dirname(os.path.abspath(__file__))
data = json.load(open(os.path.join(HERE, '..', 'dashboard_data.json')))
with open(os.path.join(HERE, 'frontend', 'data.js'), 'w') as fh:
    fh.write('window.DATA = ' + json.dumps(data, separators=(',', ':'), ensure_ascii=False) + ';\n')

def table(role):
    bowl = role == 'bowl'
    head = ('<tr><th>#</th><th>Bowler</th><th>Rating</th><th>Pressure balls</th><th>Econ (pressure / normal)</th>'
            '<th>Wkts per 100 (pressure / normal)</th></tr>') if bowl else (
           '<tr><th>#</th><th>Batter</th><th>Rating</th><th>Pressure balls</th><th>SR (pressure / normal)</th>'
           '<th>Outs per 100 (pressure / normal)</th></tr>')
    rows = []
    for p in data[role]:
        a, b = (('econ', 'wk') if bowl else ('sr', 'out'))
        da, db = (2, 1) if bowl else (0, 1)
        rows.append(f"<tr><td>{p['rank']}</td><td>{html.escape(p['name'])}</td><td>{p['final_score']:.2f}</td><td>{int(p['pb'])}</td>"
                    f"<td>{p[a+'_p']:.{da}f} / {p[a+'_n']:.{da}f}</td><td>{p[b+'_p']:.{db}f} / {p[b+'_n']:.{db}f}</td></tr>")
    return f"<h2>Top 10 {'bowlers' if bowl else 'batters'} under pressure</h2><table>{head}{''.join(rows)}</table>"

static = ('<!-- STATIC-TOP10:START (generated by build_data.py) -->\n<noscript><div class="static">'
          '<h1>ClutchRank: top 10 T20 batters and bowlers under pressure</h1>'
          '<p>Rating = 0.70·z(pressure value) + 0.15·z(consistency) + 0.15·z(clutch lift), averaged over the full data and 200 bootstrap resamples. '
          'Enable JavaScript for the interactive version.</p>'
          + table('bat') + table('bowl') + '</div></noscript>\n<!-- STATIC-TOP10:END -->')
idx = os.path.join(HERE, 'frontend', 'index.html')
s = open(idx).read()
s, n = re.subn(r'<!-- STATIC-TOP10:START.*?STATIC-TOP10:END -->', lambda m: static, s, flags=re.S)
if n == 0:
    s = s.replace('<body>\n', '<body>\n' + static + '\n', 1)
open(idx, 'w').write(s)
print('data.js written; static top-10 refreshed in index.html')
print('BAT :', ' | '.join(p['name'] for p in data['bat']))
print('BOWL:', ' | '.join(p['name'] for p in data['bowl']))
